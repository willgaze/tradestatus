'use client'

import { useCallback, useEffect, useState } from 'react'
import { HouseIcon, CopyIcon, TickIcon } from '@/components/icons'

/**
 * Switching the letterbox on, without a terminal.
 *
 * Same shape as Turn on notifications above, for the same reason: the steps
 * that need a login are the owner's, and everything either side of them should
 * be a copy button and a tappable link rather than a command to paste.
 *
 * THE TOKEN IS MADE HERE AND NOT BY ME. It is the only thing standing in front
 * of an open mail sink. Generated in a Claude session it lands in a
 * transcript; generated on a random password website it lands on somebody
 * else's server. Generated by this page it is made by the Web Crypto API on
 * the phone in the owner's hand, is never sent anywhere, and vanishes when the
 * page closes. The same reasoning as the VAPID pair, and the same answer.
 *
 * It then has to be carried to Vercel and to Cloudflare by hand, because a
 * Claude session cannot write a Vercel environment variable — the connector
 * answers 403 to that, every time it has been tried.
 *
 * The section disappears the moment forwarding is configured. It is
 * scaffolding, like the push one.
 */
const VERCEL_PROJECT =
  process.env.NEXT_PUBLIC_VERCEL_PROJECT_PATH || 'willgazes-projects/turnup'
const ENV_URL = `https://vercel.com/${VERCEL_PROJECT}/settings/environment-variables`
const DEPLOY_URL = `https://vercel.com/${VERCEL_PROJECT}/deployments`

/** 32 random bytes as base64url: unguessable, and safe in a URL path. */
const makeToken = () => {
  const bytes = crypto.getRandomValues(new Uint8Array(24))
  return btoa(String.fromCharCode(...bytes))
    .replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

function Copy({ value, label }) {
  const [done, setDone] = useState(false)
  return (
    <button
      type="button"
      onClick={async () => {
        try { await navigator.clipboard.writeText(value); setDone(true); setTimeout(() => setDone(false), 1800) }
        catch { /* older browsers: the value is on screen to select */ }
      }}
      className="btn btn-grey !min-h-[40px] !px-3 !text-[13px]"
    >
      {done ? <TickIcon size={14} /> : <CopyIcon size={14} />} {done ? 'Copied' : label}
    </button>
  )
}

function Value({ children }) {
  return (
    <p className="mt-1 break-all font-mono text-[13px]" style={{ color: 'var(--label-1)' }}>
      {children}
    </p>
  )
}

export default function InboundSetup() {
  const [configured, setConfigured] = useState(null)
  const [host, setHost] = useState('in.getturnup.com')
  const [token, setToken] = useState('')

  const read = useCallback(async () => {
    try {
      const r = await fetch('/api/dashboard/places', { cache: 'no-store' })
      const d = await r.json()
      setConfigured(Boolean(d.configured))
      if (d.host) setHost(d.host)
    } catch { setConfigured(false) }
  }, [])
  useEffect(() => { read() }, [read])

  // Nothing to say once it works, and nothing to say before we know.
  if (configured !== false) return null

  const bare = host.replace(/^[^.]+\./, '')
  const sub = host.split('.')[0]

  return (
    <section id="panel-inbound" className="glass mt-8 scroll-mt-4 overflow-hidden r-outer">
      <div className="flex items-center gap-3 px-6 py-4">
        <span className="grid h-10 w-10 shrink-0 place-items-center rounded-2xl"
              style={{ color: 'var(--tint)', background: 'color-mix(in srgb, var(--tint) 14%, transparent)' }}>
          <HouseIcon size={18} />
        </span>
        <span className="min-w-0 flex-1">
          <span className="block text-[19px] font-semibold">Turn on forwarding</span>
          <span className="block text-[14px] muted">Household cards work; nothing can post to them yet</span>
        </span>
      </div>

      <div className="px-6 pb-6 text-[15px] leading-snug muted">
        <p>
          A household card needs somewhere for forwarded email to arrive. This is free,
          and it is four things in a row. <b>Do it on a quiet evening</b> — step 2 moves
          the website&apos;s DNS, and that is the only part with any risk in it.
        </p>

        {/* The token first, because the two later steps both need it in the
            clipboard, and generating it is the one step with no waiting. */}
        <p className="mt-4 text-[12px] font-semibold uppercase tracking-wide" style={{ color: 'var(--label-3)' }}>
          First — make the password
        </p>
        {!token && (
          <button type="button" onClick={() => setToken(makeToken())}
                  className="btn accent-fill mt-2 !min-h-[44px] !px-4 !text-[14px]">
            Make it on this phone
          </button>
        )}
        {token && (
          <>
            <Value>{token}</Value>
            <div className="mt-2 flex flex-wrap gap-2"><Copy value={token} label="Copy the password" /></div>
            <p className="mt-2 text-[13px]">
              Made on this phone and sent nowhere. <b>Keep this page open</b> until step 4 —
              close it and you make a new one and start the copying again.
            </p>
          </>
        )}

        <ol className="mt-5 grid gap-5">
          <li>
            <p className="text-[12px] font-semibold uppercase tracking-wide" style={{ color: 'var(--label-3)' }}>
              1 — Give it to the website
            </p>
            <p className="mt-1">
              Open <a href={ENV_URL} target="_blank" rel="noreferrer">Vercel → Environment Variables</a>,
              press <b>Add Another</b>, and save these two:
            </p>
            <Value>INBOUND_EMAIL_TOKEN</Value>
            <Value>INBOUND_EMAIL_HOST = {host}</Value>
            <div className="mt-2 flex flex-wrap gap-2">
              <Copy value="INBOUND_EMAIL_TOKEN" label="Copy the name" />
              <Copy value="INBOUND_EMAIL_HOST" label="Copy the other name" />
              <Copy value={host} label={`Copy ${host}`} />
            </div>
            <p className="mt-2 text-[13px]">
              Then <a href={DEPLOY_URL} target="_blank" rel="noreferrer">Deployments</a> → the top
              one → <b>⋯ → Redeploy</b>. <b>You will see:</b> this whole box disappear, a minute later.
            </p>
          </li>

          <li>
            <p className="text-[12px] font-semibold uppercase tracking-wide" style={{ color: 'var(--label-3)' }}>
              2 — Move the DNS to Cloudflare
            </p>
            <p className="mt-1">
              Sign up at <a href="https://dash.cloudflare.com/sign-up" target="_blank" rel="noreferrer">Cloudflare</a>,
              add <b>{bare}</b>, choose the <b>Free</b> plan. It copies your existing records across.
            </p>
            <p className="mt-1.5">
              <b>Check the copied list has the website records in it before going on.</b> Then open
              <a href="https://hpanel.hostinger.com/" target="_blank" rel="noreferrer"> Hostinger</a> →
              Domains → {bare} → <b>Change nameservers</b>, and paste the two Cloudflare gives you.
            </p>
            <p className="mt-1.5 text-[13px]">
              <b>You will see:</b> Cloudflare says Active, usually within 15 minutes.
              Check <a href={`https://www.${bare}`} target="_blank" rel="noreferrer">the website</a> still
              loads before the next step.
            </p>
          </li>

          <li>
            <p className="text-[12px] font-semibold uppercase tracking-wide" style={{ color: 'var(--label-3)' }}>
              3 — Switch the letterbox on
            </p>
            <p className="mt-1">
              In Cloudflare, on <b>{bare}</b>: <b>Email</b> → <b>Email Routing</b> → <b>Get started</b>.
            </p>
            <p className="mt-1.5">
              Then <b>Settings</b> → add the subdomain <b>{sub}</b>. Cloudflare adds that
              subdomain&apos;s own mail records and leaves the main domain alone — which is
              the whole reason the addresses are <span className="font-mono">@{host}</span> and
              not <span className="font-mono">@{bare}</span>. Your own email, now or later,
              is never touched.
            </p>
            <p className="mt-1.5">
              Last, on <b>{host}</b>: <b>Routes</b> → turn on <b>Catch-all address</b> →
              Action <b>Send to a Worker</b> → <b>turnup-inbound</b>.
            </p>
            <p className="mt-1.5 text-[13px]">
              <b>You will see:</b> Catch-all showing as Active. Do step 4 first if the Worker
              is not in that list yet — it has to exist before it can be picked.
            </p>
          </li>

          <li>
            <p className="text-[12px] font-semibold uppercase tracking-wide" style={{ color: 'var(--label-3)' }}>
              4 — The Worker
            </p>
            <p className="mt-1">
              It is written and in the repo at <span className="font-mono text-[13px]">cloudflare/email-worker</span>.
              Someone with a laptop runs two commands; it needs the same password as step 1.
              Send them this and nothing else:
            </p>
            <Value>cd cloudflare/email-worker &amp;&amp; npx wrangler deploy</Value>
            <Value>npx wrangler secret put INBOUND_TOKEN</Value>
            <div className="mt-2 flex flex-wrap gap-2">
              <Copy value="cd cloudflare/email-worker && npx wrangler deploy" label="Copy the first" />
              <Copy value="npx wrangler secret put INBOUND_TOKEN" label="Copy the second" />
            </div>
          </li>
        </ol>

        <p className="mt-5 text-[13px]">
          <b>How you will know it all worked:</b> forward any delivery email to a card&apos;s
          address and the thing turns up on the card within a few seconds. If nothing appears,
          the email was not an arrival or a step above has not landed — not a silent failure
          you have to guess at.
        </p>
      </div>
    </section>
  )
}
